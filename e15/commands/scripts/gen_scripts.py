"""Generate the workspace's script set (SPEC §5.6) into OUTDIR.

  burn_<ms>.py   spin a CPU loop for <ms> of wall time after touching 32 MiB of heap; the
                 interpreter class and the interpreter stand-in pick among them by run time.
  edit.py        an Edit-tool stand-in: N search-and-replace edits on one file, each written
                 back atomically (temp file + rename), as editors do.
  write_tree.py  a Write-tool stand-in at scale: N files of the project's own text.
  ps.py          a `ps -e`/`top -b` stand-in (the template has no procps): scans /proc,
                 optionally for several samples.

Usage: python3 gen_scripts.py OUTDIR
Stdlib only, Python 3.9+ (the guest's UBI 9 python3).
"""

import pathlib
import sys

BURN_MS = (50, 200, 1000, 5000, 20000)
HEAP_MIB = 32

BURN = '''\
"""Generated by e15/commands/scripts/gen_scripts.py: {ms} ms of CPU after {mib} MiB of heap."""
import time

start = time.perf_counter()
heap = bytearray({mib} * 1024 * 1024)
for i in range(0, len(heap), 4096):
    heap[i] = 1
deadline = start + {ms} / 1000.0
n = 0
while time.perf_counter() < deadline:
    for _ in range(1000):
        n = (n * 1103515245 + 12345) & 0x7FFFFFFF
print("burn_{ms}", round((time.perf_counter() - start) * 1000), n)
'''

EDIT = '''\
"""Generated by e15/commands/scripts/gen_scripts.py: edit.py FILE N."""
import os
import sys

path, n = sys.argv[1], int(sys.argv[2])
for k in range(n):
    with open(path) as f:
        text = f.read()
    text = text.replace("def ", "def  ", 1) if k % 2 == 0 else text.replace("def  ", "def ", 1)
    tmp = path + ".tmp"
    with open(tmp, "w") as f:
        f.write(text)
        f.flush()
        os.fsync(f.fileno())
    os.replace(tmp, path)
print("edit", path, n)
'''

WRITE_TREE = '''\
"""Generated by e15/commands/scripts/gen_scripts.py: write_tree.py SRC OUTDIR N."""
import os
import sys

src, out, n = sys.argv[1], sys.argv[2], int(sys.argv[3])
with open(src) as f:
    text = f.read()
os.makedirs(out, exist_ok=True)
for k in range(n):
    with open(os.path.join(out, "f%04d.py" % k), "w") as f:
        f.write("# %d\\n" % k)
        f.write(text)
print("write_tree", out, n)
'''

PS = '''\
"""Generated by e15/commands/scripts/gen_scripts.py: ps.py [SAMPLES [INTERVAL_S]]."""
import os
import sys
import time

samples = int(sys.argv[1]) if len(sys.argv) > 1 else 1
interval = float(sys.argv[2]) if len(sys.argv) > 2 else 0.0
proc = "/proc"
for s in range(samples):
    rows = []
    for pid in os.listdir(proc):
        if not pid.isdigit():
            continue
        try:
            with open(os.path.join(proc, pid, "stat")) as f:
                fields = f.read().split()
            with open(os.path.join(proc, pid, "status")) as f:
                rss = next((l.split()[1] for l in f if l.startswith("VmRSS")), "0")
        except OSError:
            continue
        rows.append((int(pid), fields[1], fields[2], int(fields[13]) + int(fields[14]), rss))
    print("sample", s, "procs", len(rows))
    for row in sorted(rows):
        print("%7d %-20s %s %8d %8s" % row)
    if s + 1 < samples:
        time.sleep(interval)
'''


def main(argv):
    if len(argv) != 1:
        sys.exit("usage: gen_scripts.py OUTDIR")
    out = pathlib.Path(argv[0])
    out.mkdir(parents=True, exist_ok=True)
    for ms in BURN_MS:
        (out / f"burn_{ms}.py").write_text(BURN.format(ms=ms, mib=HEAP_MIB))
    (out / "edit.py").write_text(EDIT)
    (out / "write_tree.py").write_text(WRITE_TREE)
    (out / "ps.py").write_text(PS)


if __name__ == "__main__":
    main(sys.argv[1:])
